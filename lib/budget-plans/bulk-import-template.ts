import * as XLSX from 'xlsx';
import { BUDGET_PLAN_IMPORT_HEADERS } from '@/lib/budget-plans/bulk-import-columns';
import { getCurrentFiscalYear } from '@/lib/fiscal-year';

export type BudgetPlanImportSample = {
  fiscalYear: number;
  originOffice: string;
  departmentCode: string;
  projectCode: string;
  approvalSchemaCode: string;
};

const SAMPLE_SUBJECT = 'Monthly operating cost (sample — replace me)';
const SAMPLE_DESCRIPTION = 'Sample row. Replace subject, description, and amounts before importing.';
const SAMPLE_AMOUNT = 1_500_000;

export function defaultBudgetPlanImportSample(): BudgetPlanImportSample {
  return {
    fiscalYear: getCurrentFiscalYear(),
    originOffice: '99',
    departmentCode: 'IT',
    projectCode: 'B1',
    approvalSchemaCode: 'BP-PRIMARY',
  };
}

function instructionRows(sample: BudgetPlanImportSample): string[][] {
  return [
    ['Budget Plan bulk import'],
    [''],
    ['How to fill'],
    ['1. Use the "Budget Plans" sheet. Keep the header row. Add one row per plan.'],
    ['2. Origin Office, Department Code, Project Code, and Approval Schema Code must match master data exactly — the Code field, not the display name.'],
    [`3. Origin Office is the office code (example in this file: ${sample.originOffice}). Do not use city abbreviations unless that code exists in Origin Office master.`],
    [`4. Approval Schema Code is the short code on Workspace Management → Approval Schema (example: ${sample.approvalSchemaCode}), not "A1" and not the schema name.`],
    ['5. Project Code is optional. Leave blank if the plan has no project.'],
    ['6. Month columns are amounts in IDR. Use numbers (1500000), not text.'],
    ['7. Document numbers (IT202609001, …) are generated by the system. Do not add a Code column.'],
    ['8. Each import creates new Draft plans. Re-uploading the same file does not update existing plans.'],
    [''],
    ['The sample row on the next sheet uses codes that exist in this environment. Replace the subject and amounts with real data before importing.'],
  ];
}

function sampleDataRow(sample: BudgetPlanImportSample): (string | number)[] {
  return [
    sample.fiscalYear,
    sample.originOffice,
    sample.departmentCode,
    sample.projectCode,
    SAMPLE_SUBJECT,
    SAMPLE_DESCRIPTION,
    0,
    0,
    0,
    0,
    0,
    0,
    0,
    SAMPLE_AMOUNT,
    SAMPLE_AMOUNT,
    0,
    0,
    0,
    sample.approvalSchemaCode,
  ];
}

export function buildBudgetPlanImportWorkbook(sample: BudgetPlanImportSample = defaultBudgetPlanImportSample()) {
  const workbook = XLSX.utils.book_new();

  const dataSheet = XLSX.utils.aoa_to_sheet([
    [...BUDGET_PLAN_IMPORT_HEADERS],
    sampleDataRow(sample),
  ]);
  dataSheet['!cols'] = BUDGET_PLAN_IMPORT_HEADERS.map((header) => ({
    wch: Math.max(14, header.length + 2),
  }));
  // First sheet must be the data grid — the upload parser reads SheetNames[0]
  // unless a sheet named "Budget Plans" exists.
  XLSX.utils.book_append_sheet(workbook, dataSheet, 'Budget Plans');

  const instructionSheet = XLSX.utils.aoa_to_sheet(instructionRows(sample));
  instructionSheet['!cols'] = [{ wch: 120 }];
  XLSX.utils.book_append_sheet(workbook, instructionSheet, 'Instructions');

  return workbook;
}

export function buildBudgetPlanImportWorkbookBuffer(
  sample: BudgetPlanImportSample = defaultBudgetPlanImportSample(),
): Buffer {
  const workbook = buildBudgetPlanImportWorkbook(sample);
  return XLSX.write(workbook, { type: 'buffer', bookType: 'xlsx' }) as Buffer;
}
